`timescale 1ns / 1ps

module rom (
    input  logic [31:0] addr,
    output logic [31:0] data
);
    logic [31:0] rom[0:15];

    initial begin
        



        rom[0] = 32'b0100000_00011_00010_000_00001_0110011;
        // B-type에는 SUB 연산이 없어 R-type 사용해 음수 생성
        //B-Type    imm7     rs2   rs1 fucnt3 imm5 opcode
        rom[1] = 32'b0000000_00010_00010_000_01000_1100011;

        rom[3] = 32'b0000000_00010_00011_001_01000_1100011; // sub  x1(rd), x2(rs1),  x10(rs2)

        rom[5] = 32'b0000000_00010_00001_100_01000_1100011; // sll  x2(rd), x1(rs1),  x3(rs2)

        rom[7] = 32'b0000000_00010_00001_110_01000_1100011; // srl  x3(rd), x2(rs1),  x4(rs2)

        rom[8] = 32'b0000000_00010_00001_101_01000_1100011; // sra  x4(rd), x1(rs1),  x5(rs2)

        rom[9] = 32'b0000000_00010_00001_111_01000_1100011; // slt  x5(rd), x4(rs1),  x7(rs2)


    end

    assign data = rom[addr[31:2]];
endmodule
















