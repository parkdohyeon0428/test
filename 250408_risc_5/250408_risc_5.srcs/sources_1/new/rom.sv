`timescale 1ns / 1ps

module rom(
    input logic [31:0] addr,
    output logic [31:0] data
);
    logic [31:0] rom[0:15];

    initial begin
        //rom[x] = 32'b fucn7 _ rs2 _ rs1 _ f3 _ rd _ opcode; // r type
        rom[0] = 32'b0000000_00001_00010_000_00100_0110011; // add x4 x2 x1
        rom[1] = 32'b0100000_00001_00010_000_00100_0110011; // add x4 x2 x1
        rom[2] = 32'b0000000_00001_00010_001_00100_0110011; // add x4 x2 x1
        rom[3] = 32'b0000000_00001_00010_101_00100_0110011; // add x4 x2 x1
        rom[4] = 32'b0100000_00001_00010_101_00100_0110011; // add x4 x2 x1
        rom[5] = 32'b0000000_00001_00010_010_00100_0110011; // add x4 x2 x1
        rom[6] = 32'b0000000_00001_00010_011_00100_0110011; // add x4 x2 x1
        rom[7] = 32'b0000000_00001_00010_100_00100_0110011; // add x4 x2 x1
        rom[8] = 32'b0000000_00001_00010_110_00100_0110011; // add x4 x2 x1
        rom[9] = 32'b0000000_00001_00010_111_00100_0110011; // add x4 x2 x1
        
        
    end

    assign data = rom[addr[31:2]];  //4의 배수로 가기위해 하위 두비트 버림
endmodule
